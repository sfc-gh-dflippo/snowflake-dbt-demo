//! The generated rule catalog (`dbt-quality rules --format markdown`).
//!
//! Prose that is not per-rule lives in `rules/catalog-preamble.md` and
//! `rules/catalog-appendix.md`; everything per-rule comes from the records.

use std::fmt::Write as _;

use crate::model::{RuleMeta, RULES};
use crate::report::category_label;

const PREAMBLE: &str = include_str!("../../../../rules/catalog-preamble.md");
const APPENDIX: &str = include_str!("../../../../rules/catalog-appendix.md");

pub fn sorted() -> Vec<&'static RuleMeta> {
    let mut r: Vec<&RuleMeta> = RULES.iter().collect();
    r.sort_by_key(|m| m.code);
    r
}

fn cell(s: &str) -> String {
    s.replace('|', "\\|").replace('\n', " ")
}

fn pack_tier(pack: &str) -> String {
    let mut tiers: Vec<&str> = RULES.iter().filter(|r| r.pack == pack).map(|r| r.tier).collect();
    tiers.sort();
    tiers.dedup();
    if tiers.len() == 1 { format!("`{}`", tiers[0]) } else { "`mixed`".into() }
}

/// The full catalog as Markdown. Committed as `rule-catalog.md`;
/// `scripts/check-catalog.sh` fails when the committed copy differs.
pub fn markdown() -> String {
    let mut o = String::from(
        "# Rule Catalog\n\n<!-- Generated by `dbt-quality rules --format markdown` from rules/*.json. Do not edit by hand. -->\n\n\
         Every rule, the practice it protects, and the signal that detects it. Load this when a user asks why a rule \
         fired, disputes a suggestion, or you are adding a rule. For one rule's full record — long description, \
         remediation and examples — run `dbt-quality rules --code <CODE>` or call the MCP `rules` tool with `code`.\n\n",
    );
    o.push_str(PREAMBLE);
    let mut packs: Vec<&str> = RULES.iter().map(|r| r.pack).collect();
    packs.sort();
    packs.dedup();
    for pack in packs {
        let _ = write!(
            o,
            "\n---\n\n## {pack} — {} {}\n\n| Rule | Kind | Level | Severity | Tier | Scope | Name | Signal |\n| ---- | ---- | ----- | -------- | ---- | ----- | ---- | ------ |\n",
            category_label(pack),
            pack_tier(pack)
        );
        for m in sorted().into_iter().filter(|m| m.pack == pack) {
            let _ = writeln!(
                o,
                "| {} | {} | {} | {} | {} | {} | {} | {} |",
                m.code, m.kind, m.level, m.severity, m.tier, m.scope, cell(m.name), cell(m.short_description)
            );
        }
    }
    o.push_str(APPENDIX);
    o
}
