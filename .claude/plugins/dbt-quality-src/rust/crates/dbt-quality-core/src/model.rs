//! Core types: levels, rule metadata, suggestions.
//!
//! Each suggestion has an issue family (`kind`: EWI/FDM/PRF), a confidence
//! level (`level`: error/warning/information), and an impact rating
//! (`severity`: critical/high/medium/low). Severity assumes the finding is valid.

use serde::Serialize;
use serde_json::{Map, Value};

use crate::sqlutil::TextSpan;

pub mod level {
    pub const ERROR: &str = "error";
    pub const WARNING: &str = "warning";
    pub const INFORMATION: &str = "information";
}

pub mod severity {
    pub const CRITICAL: &str = "critical";
    pub const HIGH: &str = "high";
    pub const MEDIUM: &str = "medium";
    pub const LOW: &str = "low";
}

pub mod tier {
    pub const UNIVERSAL: &str = "universal";
    pub const ARCHITECTURE: &str = "architecture";
    pub const MIGRATION: &str = "migration";
}

pub mod effort {
    pub const LOW: &str = "low";
    pub const MEDIUM: &str = "medium";
    pub const HIGH: &str = "high";
}

pub fn level_rank(level: &str) -> u8 {
    match level {
        level::ERROR => 0,
        level::WARNING => 1,
        level::INFORMATION => 2,
        _ => 9,
    }
}

pub fn severity_rank(s: &str) -> u8 {
    match s {
        severity::CRITICAL => 0,
        severity::HIGH => 1,
        severity::MEDIUM => 2,
        severity::LOW => 3,
        _ => 9,
    }
}

pub fn effort_rank(e: &str) -> u8 {
    match e {
        effort::LOW => 1,
        effort::HIGH => 3,
        _ => 2,
    }
}

/// Convert a level to a VS Code problem-matcher token.
pub fn lint_token(level: &str) -> &'static str {
    match level {
        level::ERROR => "error",
        level::WARNING => "warning",
        _ => "info",
    }
}

/// Count a noun: `1 model`, `3 models`.
pub fn plural(count: usize, singular: &str) -> String {
    plural_irregular(count, singular, &format!("{singular}s"))
}

pub fn plural_irregular(count: usize, singular: &str, many: &str) -> String {
    format!("{count} {}", if count == 1 { singular } else { many })
}

#[derive(Debug, Clone, Copy, Serialize)]
pub struct Example {
    pub title: &'static str,
    pub bad: &'static str,
    pub good: &'static str,
}

#[derive(Debug, Clone, Copy, Serialize)]
pub struct Reference {
    pub title: &'static str,
    pub url: &'static str,
}

/// One rule's metadata, generated by `build.rs` from `rules/<PACK>.json`.
#[derive(Debug, Clone, Copy, Serialize)]
pub struct RuleMeta {
    pub code: &'static str,
    pub pack: &'static str,
    pub number: u32,
    pub kind: &'static str,
    pub name: &'static str,
    pub short_description: &'static str,
    pub long_description: &'static str,
    pub remediation: &'static str,
    pub level: &'static str,
    pub severity: &'static str,
    pub tier: &'static str,
    pub scope: &'static str,
    pub effort: &'static str,
    /// Each finding is its own edit, so a file may repeat the remediation.
    pub per_line: bool,
    pub anti_patterns: &'static [&'static str],
    pub principles: &'static [&'static str],
    pub marker_subject: Option<&'static str>,
    pub examples: &'static [Example],
    pub references: &'static [Reference],
    pub since: &'static str,
    pub status: &'static str,
    /// The record exactly as written in the pack file.
    #[serde(skip)]
    pub json: &'static str,
}

include!(concat!(env!("OUT_DIR"), "/rules_meta.rs"));

pub fn meta(code: &str) -> Option<&'static RuleMeta> {
    RULES.iter().find(|r| r.code == code)
}

/// The category (pack) letters of a code: `SSC-EWI-DBTINC0002` -> `INC`.
pub fn pack_of(code: &str) -> &str {
    code.get(11..14).unwrap_or("")
}

/// A single audit suggestion. Field names and the JSON shape follow the
/// Python `Suggestion.to_dict` contract.
#[derive(Debug, Clone)]
pub struct Suggestion {
    pub rule_id: String,
    pub title: String,
    pub kind: String,
    pub level: String,
    pub severity: String,
    pub tier: String,
    pub category: String,
    pub message: String,
    pub project: String,
    /// The root-relative directory of the project; empty for estate findings.
    pub project_path: String,
    pub file: String,
    pub line: Option<u32>,
    pub column: Option<u32>,
    pub end_line: Option<u32>,
    pub end_column: Option<u32>,
    pub evidence: String,
    pub remediation: String,
    pub effort: String,
    pub context: Map<String, Value>,
    pub suppressed: bool,
    pub suppressed_reason: String,
}

impl Suggestion {
    /// Build a suggestion that inherits its rule's metadata.
    ///
    /// Panics on an unknown code: every detector's code has a record, which a
    /// unit test enforces.
    pub fn new(code: &str, message: impl Into<String>) -> Self {
        let m = meta(code).unwrap_or_else(|| panic!("no metadata record for {code}"));
        Suggestion {
            rule_id: m.code.to_string(),
            title: m.name.to_string(),
            kind: m.kind.to_string(),
            level: m.level.to_string(),
            severity: m.severity.to_string(),
            tier: m.tier.to_string(),
            category: m.pack.to_string(),
            message: message.into(),
            project: String::new(),
            project_path: String::new(),
            file: String::new(),
            line: None,
            column: None,
            end_line: None,
            end_column: None,
            evidence: String::new(),
            remediation: m.remediation.to_string(),
            effort: effort::MEDIUM.to_string(),
            context: Map::new(),
            suppressed: false,
            suppressed_reason: String::new(),
        }
    }

    pub fn file(mut self, f: impl Into<String>) -> Self {
        self.file = f.into();
        self
    }
    pub fn project(mut self, p: impl Into<String>) -> Self {
        self.project = p.into();
        self
    }
    /// Attach the suggestion to a project: its label and its root-relative path.
    pub fn in_project(mut self, p: &crate::discovery::ProjectContext) -> Self {
        self.project = p.label.clone();
        self.project_path = p.relative_root.clone();
        self
    }
    pub fn line(mut self, l: u32) -> Self {
        self.line = Some(l);
        self
    }
    pub fn line_opt(mut self, l: Option<u32>) -> Self {
        self.line = l;
        self
    }
    /// Line plus column, with no end position.
    pub fn at(mut self, (line, column): (u32, u32)) -> Self {
        self.line = Some(line);
        self.column = Some(column);
        self
    }
    pub fn span(mut self, s: TextSpan) -> Self {
        self.line = Some(s.line);
        self.column = Some(s.column);
        self.end_line = Some(s.end_line);
        self.end_column = Some(s.end_column);
        self
    }
    pub fn level(mut self, l: &str) -> Self {
        self.level = l.to_string();
        self
    }
    pub fn severity(mut self, s: &str) -> Self {
        self.severity = s.to_string();
        self
    }
    pub fn evidence(mut self, e: impl Into<String>) -> Self {
        self.evidence = e.into();
        self
    }
    pub fn remediation(mut self, r: impl Into<String>) -> Self {
        self.remediation = r.into();
        self
    }
    pub fn effort(mut self, e: &str) -> Self {
        self.effort = e.to_string();
        self
    }
    pub fn ctx(mut self, k: &str, v: impl Into<Value>) -> Self {
        self.context.insert(k.to_string(), v.into());
        self
    }

    pub fn to_json(&self) -> Value {
        let mut out = Map::new();
        for (k, v) in [
            ("rule_id", &self.rule_id),
            ("title", &self.title),
            ("kind", &self.kind),
            ("level", &self.level),
            ("severity", &self.severity),
            ("tier", &self.tier),
            ("category", &self.category),
            ("message", &self.message),
            ("project", &self.project),
            ("file", &self.file),
            ("evidence", &self.evidence),
            ("remediation", &self.remediation),
            ("effort", &self.effort),
        ] {
            out.insert(k.into(), Value::String(v.clone()));
        }
        if !self.project_path.is_empty() {
            out.insert("project_path".into(), self.project_path.clone().into());
        }
        if let Some(l) = self.line {
            out.insert("line".into(), l.into());
        }
        for (k, v) in [("column", self.column), ("end_line", self.end_line), ("end_column", self.end_column)] {
            if let Some(v) = v.filter(|v| *v != 0) {
                out.insert(k.into(), v.into());
            }
        }
        if !self.context.is_empty() {
            out.insert("context".into(), Value::Object(self.context.clone()));
        }
        if self.suppressed {
            out.insert("suppressed".into(), true.into());
            out.insert("suppressed_reason".into(), self.suppressed_reason.clone().into());
        }
        Value::Object(out)
    }
}

#[cfg(test)]
mod tests {
    use std::collections::BTreeSet;

    use super::*;
    use crate::html::safe_reference_url;

    fn reference_contract(description: &str, references: &[Reference]) -> Result<(), &'static str> {
        if references.is_empty() {
            return Err("references are missing");
        }
        let mut urls = BTreeSet::new();
        for reference in references {
            if reference.title.trim().is_empty() {
                return Err("reference title is empty");
            }
            if !safe_reference_url(reference.url) {
                return Err("reference URL is unsafe");
            }
            if !urls.insert(reference.url) {
                return Err("reference URL is repeated");
            }
        }
        // Packs use plain, colon, or Markdown headings. Bullet text must match exactly.
        let Some((guidance, bullets)) = ["\n\nReferences\n", "\n\nReferences:\n", "\n\n## References\n\n"]
            .iter().find_map(|heading| description.split_once(heading)) else {
                return Err("References section is missing");
            };
        if guidance.trim().is_empty() {
            return Err("guidance is missing");
        }
        let expected = references.iter().map(|reference| format!("- [{}]({})", reference.title, reference.url)).collect::<Vec<_>>().join("\n");
        if bullets != expected {
            return Err("References bullets differ from structured references");
        }
        Ok(())
    }

    fn marker_safe_name(name: &str) -> bool {
        !name.trim().is_empty()
            && name.chars().count() <= 60
            && !name.chars().any(|character| character.is_control() || matches!(character, '\u{2028}' | '\u{2029}'))
            && !["{{", "}}", "{%", "%}", "{#", "#}", "**", "/*", "*/", "<!--", "-->"].iter().any(|delimiter| name.contains(delimiter))
    }

    #[test]
    fn reference_metadata_covers_all_rules() {
        assert_eq!(RULES.len(), 124);
        for rule in RULES {
            assert_eq!(reference_contract(rule.long_description, rule.references), Ok(()), "{}", rule.code);
            assert!(marker_safe_name(rule.name), "{} has an unsafe name: {:?}", rule.code, rule.name);
            assert!(!rule.short_description.trim().is_empty(), "{} has an empty short description", rule.code);
            assert!(rule.short_description.chars().count() <= 160, "{} has a long short description", rule.code);
        }
    }

    #[test]
    fn reference_metadata_matches_source_records() {
        for rule in RULES {
            let source: Value = serde_json::from_str(rule.json).unwrap();
            assert_eq!(source["name"], rule.name, "{} name", rule.code);
            assert_eq!(source["short_description"], rule.short_description, "{} short description", rule.code);
            assert_eq!(source["long_description"], rule.long_description, "{} long description", rule.code);
            assert_eq!(source["references"], serde_json::to_value(rule.references).unwrap(), "{} references", rule.code);
        }
    }

    #[test]
    fn reference_metadata_rejects_missing_and_mismatched_bullets() {
        let references = [Reference { title: "dbt ref", url: "https://docs.getdbt.com/reference/dbt-jinja-functions/ref" }];
        let valid = "Use ref().\n\nReferences\n- [dbt ref](https://docs.getdbt.com/reference/dbt-jinja-functions/ref)";
        for heading in ["References\n", "References:\n", "## References\n\n"] {
            assert_eq!(reference_contract(&valid.replace("References\n", heading), &references), Ok(()));
        }
        assert_eq!(reference_contract(valid, &[]), Err("references are missing"));
        assert_eq!(reference_contract("Use ref().", &references), Err("References section is missing"));
        assert_eq!(reference_contract("\n\nReferences\n- [dbt ref](https://docs.getdbt.com/reference/dbt-jinja-functions/ref)", &references), Err("guidance is missing"));
        for invalid in [
            valid.replace("[dbt ref]", "[Other title]"),
            format!("{valid}\n- [Extra source](https://example.com)"),
            valid.replace("functions/ref)", "functions/source)"),
            valid.replace("- [", "* ["),
            valid.replace("\n- [dbt ref](https://docs.getdbt.com/reference/dbt-jinja-functions/ref)", ""),
            format!("{valid}\n\nReferences\n- [dbt ref](https://docs.getdbt.com/reference/dbt-jinja-functions/ref)"),
        ] {
            assert!(reference_contract(&invalid, &references).is_err(), "accepted {invalid:?}");
        }
        let two_references = [references[0], Reference { title: "dbt source", url: "https://docs.getdbt.com/reference/dbt-jinja-functions/source" }];
        let reversed = "Use ref().\n\nReferences\n- [dbt source](https://docs.getdbt.com/reference/dbt-jinja-functions/source)\n- [dbt ref](https://docs.getdbt.com/reference/dbt-jinja-functions/ref)";
        assert!(reference_contract(reversed, &two_references).is_err());
    }

    #[test]
    fn reference_metadata_rejects_empty_titles_and_duplicate_urls() {
        for title in ["", " \t\n"] {
            let references = [Reference { title, url: "https://docs.getdbt.com" }];
            assert_eq!(reference_contract("", &references), Err("reference title is empty"));
        }
        let references = [
            Reference { title: "dbt", url: "https://docs.getdbt.com" },
            Reference { title: "Same URL, different label", url: "https://docs.getdbt.com" },
        ];
        assert_eq!(reference_contract("", &references), Err("reference URL is repeated"));
    }

    #[test]
    fn reference_metadata_uses_report_url_policy() {
        for url in [
            "", "/relative", "//example.com", "http://example.com", "javascript:alert(1)", "data:text/html,test", "file:///tmp/source",
            "https:example.com", "https://", "https://user:password@example.com", "https://user@example.com", "https://example.com:invalid",
            "https://example.com/has space", " https://example.com", "https://example.com\n", "https://example.com/\0", "https://example.com/\\path",
            "https://example.com/%", "https://example.com/%a", "https://example.com/%xy",
        ] {
            let references = [Reference { title: "Source", url }];
            assert_eq!(reference_contract("", &references), Err("reference URL is unsafe"), "{url:?}");
        }
        for url in ["https://docs.getdbt.com/reference/ref#advanced", "https://docs.snowflake.com/en/sql-reference?topic=a%20b"] {
            let references = [Reference { title: "Source", url }];
            let description = format!("Review the source.\n\nReferences\n- [Source]({url})");
            assert_eq!(reference_contract(&description, &references), Ok(()));
        }
    }

    #[test]
    fn reference_metadata_names_reject_marker_and_jinja_delimiters() {
        for name in ["", "   ", "first\nsecond", "first\rsecond", "first\tsecond", "null\0byte", "line\u{2028}break", "line\u{2029}break"] {
            assert!(!marker_safe_name(name), "{name:?}");
        }
        for delimiter in ["{{", "}}", "{%", "%}", "{#", "#}", "**", "/*", "*/", "<!--", "-->"] {
            assert!(!marker_safe_name(&format!("name {delimiter} suffix")), "{delimiter}");
        }
        assert!(marker_safe_name(&"x".repeat(60)));
        assert!(!marker_safe_name(&"x".repeat(61)));
        assert!(marker_safe_name(&"\u{e9}".repeat(60)), "length is measured in characters");
        assert!(marker_safe_name("ref() uses a version argument"));
    }
}
